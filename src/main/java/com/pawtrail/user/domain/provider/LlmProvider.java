package com.pawtrail.user.domain.provider;

import com.pawtrail.user.domain.provider.dto.SummaryData;

/**
 * 하루 요약 문장을 만들어 오는 약속입니다.
 *
 * external 아래 구현이 붙습니다.
 * 우리가 만든 다른 서비스가 아니라 바깥 시스템이기 때문이며,
 * 프로필 사진을 다루는 StorageProvider 와 같은 자리입니다.
 *
 * 실패하면 null 을 돌려줍니다. 예외를 던지지 않습니다.
 * 실패 처리를 부르는 쪽이 정하는 것이 이 프로젝트의 규칙입니다.
 * 다만 이 값은 즐겨찾기의 판정이나 평점과 달라서, 부르는 쪽도 결국 요청을 실패시킵니다.
 * 빈 문장을 저장하면 그것이 화면에 그대로 뜨기 때문입니다.
 *
 * 다시 만들 수 있는 값이라는 점이 방문 기록의 판정과 다릅니다.
 * 그쪽은 방문 시점을 박아 두는 것이라 한 번 틀리면 영영 틀린 채로 남지만,
 * 요약은 사용자가 갱신 버튼을 다시 누르면 새로 만들어집니다.
 *
 * 재시도를 여기서 하지 않습니다.
 * 그 버튼이 곧 재시도이고, 서버가 한 번 더 부르면 응답이 두 배로 길어집니다.
 */
public interface LlmProvider {

    /**
     * 하루치 재료로 요약 문장 하나를 만듭니다.
     *
     * 길이 검사는 여기서 합니다.
     * 정해진 길이를 넘겨서 왔다는 것은 모델이 지시를 흘렸다는 뜻이라
     * 그 결과를 부르는 쪽에 넘길 이유가 없습니다.
     * 잘라서 돌려주지도 않습니다. "평균 별점은 4." 처럼 끊긴 문장이 화면에 남습니다.
     *
     * 아래 경우에 모두 null 이 돌아옵니다.
     *   호출이 실패하거나 제한 시간을 넘김
     *   응답에서 문장을 꺼내지 못함
     *   문장이 정해진 길이를 넘김
     *
     * 셋을 구분하지 않는 것은 부르는 쪽이 할 일이 같기 때문입니다.
     * 어느 경우든 저장하지 않고 사용자에게 다시 시도하라고 알립니다.
     */
    String summarize(SummaryData data);
}
