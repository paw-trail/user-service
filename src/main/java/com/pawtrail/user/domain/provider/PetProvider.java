package com.pawtrail.user.domain.provider;

import java.util.UUID;

/**
 * pet 서비스에서 반려동물 소유권을 확인하는 약속입니다.
 *
 * 다른 provider 넷과 성격이 하나 다릅니다.
 * 그쪽은 화면에 채울 값을 받아 오지만 이쪽은 저장해도 되는지를 묻습니다.
 * 그래서 실패했을 때 할 일도 반대입니다.
 * 장소나 평점은 못 받아도 카드를 그리면 되지만,
 * 소유권을 확인하지 못한 채로 저장하면 지금까지 막아 온 구멍이 그대로 열립니다.
 *
 * 값을 담아 돌려주지 않고 참거짓만 돌려줍니다.
 * 우리가 묻는 것이 "이 사람 것인가" 하나뿐이고 이름도 체중도 쓰지 않습니다.
 * 안 쓰는 값을 받아 두지 않는 것은 즐겨찾기 카드에서 주소를 뺀 것과 같은 기준입니다.
 */
public interface PetProvider {

    /**
     * 그 반려동물이 부른 사람의 것인지 확인합니다.
     *
     * pet 은 없는 반려동물과 남의 반려동물을 모두 404 로 돌려줍니다.
     * 남의 것을 없는 것처럼 다루면 존재 여부도 새지 않는다는 판단이며,
     * 받는 쪽에서도 둘을 가릴 방법이 없고 가릴 이유도 없습니다.
     * 어느 쪽이든 저장하면 안 되는 값이므로 거짓 하나로 모읍니다.
     *
     * 호출 자체가 실패하면 거짓이 아니라 예외를 던집니다.
     * 거짓으로 돌려주면 pet 이 잠깐 죽은 것과 남의 반려동물을 넣은 것이 같은 응답이 되어,
     * 사용자에게는 자기 반려동물이 없다고 안내되고 로그에도 장애가 남지 않습니다.
     * 던지는 것은 UserErrorCode.PET_UNAVAILABLE 이고 502 로 나갑니다.
     *
     * 실패 해석을 여기서 정하는 것은 호출이 실패했다는 사실을 이 계층만 알기 때문입니다.
     * 연결 거부인지 시간 초과인지 유레카가 서비스를 못 찾은 것인지는 부르는 쪽이 알 수 없고,
     * 알아도 할 일이 하나로 같습니다.
     *
     * @param petId 확인할 반려동물 식별자입니다. null 을 넘기지 않습니다.
     * @return 부른 사람의 것이면 참, 없거나 남의 것이면 거짓입니다.
     */
    boolean isOwned(UUID petId);
}
