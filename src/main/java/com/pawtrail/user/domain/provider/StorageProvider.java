package com.pawtrail.user.domain.provider;

import java.util.UUID;

/**
 * 객체 저장소와 이야기하는 약속입니다.
 *
 * 이 인터페이스에 S3 라는 단어가 나오지 않습니다.
 * 무엇을 할 수 있는지만 적고 어떻게 하는지는 infrastructure 가 정합니다.
 * 나중에 다른 저장소로 옮겨도 도메인은 그대로입니다.
 *
 * 키를 만드는 규칙도 여기 둡니다.
 * 발급할 때와 검증할 때가 같은 규칙을 써야 하는데,
 * 두 곳에 따로 적으면 한쪽만 고쳐질 자리가 됩니다.
 */
public interface StorageProvider {

    /**
     * 그 계정의 프로필 사진이 놓일 자리를 알려줍니다.
     *
     * 계정당 하나로 고정입니다. 확장자도 없습니다.
     *   users/{accountId}/profile
     *
     * 고정한 이유는 새 사진이 덮어써지게 하기 위해서입니다.
     * 매번 새 키를 쓰면 옛 파일을 지워야 하고, 지우려면 그것이 내 파일인지 검증해야 합니다.
     * 사용자가 보낸 주소를 믿고 지우면 남의 파일을 지우는 도구가 됩니다.
     *
     * 확장자를 안 붙이는 이유는 그것이 파일 이름의 관습일 뿐이기 때문입니다.
     * 브라우저는 Content-Type 헤더를 보고 그립니다.
     * .jpg 로 고정하면 PNG 를 올렸을 때 이름과 내용이 어긋나고,
     * 요청에서 받으면 .jpg 와 .png 두 파일이 남습니다.
     *
     * 이 값이 곧 정답입니다.
     * 저장 요청이 들고 온 키가 이것과 다르면 거부합니다.
     */
    String profileImageKey(UUID accountId);

    /**
     * 그 자리의 서명 없는 주소를 만듭니다.
     *
     * 두 자리에 씁니다.
     *   업로드 응답의 fileUrl — 프론트가 PATCH /users/me 에 담아 보낼 값
     *   저장 요청 검증 — 들고 온 값이 이것과 같은지 봄
     *
     * 이 주소로는 파일이 안 열립니다. 버킷이 퍼블릭 액세스를 차단해 두었기 때문입니다.
     * 보는 것은 presignDownload 가 만든 서명된 주소로만 됩니다.
     *
     * 그래도 이 형태를 주고받는 이유는 명세가 fileUrl 을 주소로 정했기 때문이고,
     * 키만 주고받으면 프론트가 그것을 어디에 쓸지 알기 어렵기 때문입니다.
     */
    String publicUrl(String key);

    /**
     * 브라우저가 그 자리에 파일을 올릴 수 있는 주소를 만듭니다.
     *
     * 이 서버는 파일을 받지 않습니다. 주소만 만들어 주고 브라우저가 S3 로 직접 PUT 합니다.
     * 그래서 서버가 파일 크기만큼의 메모리도 대역폭도 쓰지 않습니다.
     *
     * contentType 을 서명에 넣습니다.
     * 그러면 브라우저는 그 타입으로만 올릴 수 있고,
     * S3 가 그 값을 객체에 저장해 두었다가 조회할 때 그대로 돌려줍니다.
     * 확장자가 없어도 브라우저가 형식을 아는 것이 이 때문입니다.
     *
     * contentLength 도 서명에 넣습니다.
     * 그 크기가 아닌 요청은 S3 가 거부하므로 클라이언트 검증에 기대지 않게 됩니다.
     *
     * presigned PUT 에는 크기 범위를 걸 수 없어 정확한 값을 받습니다.
     * 범위 조건(content-length-range)은 presigned POST 의 폼 정책에만 있고,
     * 버킷 정책에도 크기를 보는 조건 키가 없습니다.
     * 상한 자체는 부르는 쪽이 봅니다. 서명은 "요청한 크기와 다른 것" 만 막습니다.
     */
    String presignUpload(String key, String contentType, long contentLength);

    /**
     * 그 자리의 파일을 볼 수 있는 주소를 만듭니다.
     *
     * 버킷이 퍼블릭 액세스를 차단해 두었으므로 서명 없이는 열리지 않습니다.
     * 서명이 매번 달라 브라우저 캐시 문제도 함께 풀립니다.
     * 키가 고정이라 주소가 안 바뀌면 사진을 바꿔도 옛것이 보일 자리였습니다.
     *
     * 대신 캐시가 안 되어 화면을 열 때마다 다시 받습니다.
     * 트래픽이 문제가 되면 CloudFront 를 앞에 두게 되는데,
     * 그때도 저장해 둔 값은 키뿐이라 이 메서드만 바꾸면 됩니다.
     */
    String presignDownload(String key);

    /**
     * 그 자리의 파일을 지웁니다.
     *
     * 평소에는 부를 일이 없습니다. 사진을 바꾸면 덮어써지기 때문입니다.
     * 탈퇴 처리에서만 씁니다.
     *
     * 없는 키를 지워도 S3 는 오류를 내지 않습니다.
     * 사진을 안 올린 사람의 탈퇴도 그대로 지나갑니다.
     */
    void delete(String key);
}
