package com.pawtrail.user.domain.exception;

import com.pawtrail.common.exception.ErrorCode;
import org.springframework.http.HttpStatus;

/**
 * 이 서비스의 도메인 에러 코드입니다.
 *
 * 공통 코드는 CommonErrorCode 에 있고 도메인 개념은 여기에 둡니다.
 * 공통에 두면 코드 하나를 더할 때마다 공통 모듈 재배포와 전 서비스 버전업이 필요해집니다.
 *
 * getCode 는 반드시 name 을 그대로 반환합니다.
 * 상수 이름이 곧 응답의 code 값이자 API 계약인데, 규칙을 어겨도 컴파일러가 잡지 못합니다.
 *
 * 메시지는 고정 문자열입니다. 동적인 값이 필요하면 응답 data 에 담습니다.
 *
 * 이 파일은 방문 기록에서 처음 생겼습니다.
 * 그전까지는 CommonErrorCode 여섯 개로 충분했습니다.
 * 프로필도 즐겨찾기도 실패가 "값이 잘못됐다" 나 "없다" 로 표현되는 것뿐이었고,
 * 우리가 이름을 붙여야 하는 실패가 처음 나온 자리가 여기입니다.
 *
 * 공통 코드를 쓸지 여기에 둘지는 메시지가 상황을 맞게 말하는가로 가릅니다.
 * 상태 코드가 같아도 사용자에게 보일 문구가 어긋나면 여기에 둡니다.
 *
 * 하루 요약의 셋은 그 기준이 아니라 다른 이유로 여기 있습니다.
 * 명세가 이름을 이미 정해 두었고, 공통 코드에 429 자체가 없습니다.
 */
public enum UserErrorCode implements ErrorCode {

    // ── 방문 기록 ─────────────────────────────────────────────
    // 판정 서비스가 응답하지 않아 방문 기록을 만들지 못함
    //
    // * 왜 요청 자체를 실패시키는가
    //   verdict_at_visit 은 방문 시점의 판정을 박아 두는 값임
    //   조건이 바뀌어도 안 바뀌는 것이 존재 이유라 한 번 잘못 들어가면
    //   영구히 잘못되고 고치는 API 도 없음
    //   [다녀왔어요] 는 며칠 전 일정을 지금 기록하는 동작이라
    //   몇 분 뒤에 다시 눌러도 사용자가 잃는 것이 없음
    //
    // * UNKNOWN 으로 채우지 않는 이유
    //   그 값은 이미 "펫이 0마리라 판단할 조건 정보가 없음" 이라는 뜻임
    //   서버 장애를 거기에 섞으면 나중에 그 기록을 보고 어느 쪽인지 알 방법이 없음
    //
    // * 즐겨찾기와 정반대임
    //   거기는 판정을 못 받아도 배지만 비우고 목록을 내려보냄
    //   "내가 담아둔 곳 목록" 이라는 화면의 목적이 배지 없이도 이뤄지기 때문임
    //   실패 처리를 공통 모듈에 두지 않고 부르는 쪽이 정하게 한 이유가 이것임
    //
    // * CommonErrorCode.EXTERNAL_API_ERROR 를 쓰지 않는 이유
    //   같은 502 이지만 즐겨찾기 목록의 실패와 코드가 같아짐
    //   프론트가 "목록을 못 불러왔어요" 와 "판정을 못 받아 기록하지 못했어요" 를
    //   가려서 안내해야 하는데 코드가 같으면 경로로만 판단하게 됨
    //
    // * 이름에 API 를 넣지 않은 이유
    //   일정도 판정을 부르므로 그때 같은 코드를 그대로 씀
    VERDICT_UNAVAILABLE(HttpStatus.BAD_GATEWAY, "판정을 불러오지 못해 기록하지 못했습니다."),

    // 그 방문 기록이 없거나 내 것이 아님
    //
    // * 두 경우에 같은 코드를 씀
    //   403 을 내면 "그 visitId 는 존재하는데 네 것이 아니다" 를 알려주는 셈이라
    //   식별자를 넣어 보며 존재를 확인할 수 있게 됨
    //   조회를 accountId 와 함께 하므로 서비스도 두 경우를 구분하지 않음
    //
    // * CommonErrorCode.RESOURCE_NOT_FOUND 를 쓰지 않는 이유
    //   그 코드의 메시지가 "요청하신 경로를 찾을 수 없습니다" 임
    //   없는 URL 을 불렀을 때 쓰려고 만든 것이라 여기서는 뜻이 어긋남
    //   프론트가 그 문구를 그대로 띄우면 사용자가 주소가 잘못된 줄로 읽음
    //
    // * 정상 흐름에서도 나올 수 있는 자리임
    //   삭제 버튼은 목록에 있는 카드에만 붙지만
    //   더블클릭이나 두 탭에서 이미 지운 것을 다시 지우려는 요청이 나감
    VISIT_NOT_FOUND(HttpStatus.NOT_FOUND, "이미 삭제되었거나 없는 기록입니다."),

    // ── 일정 ─────────────────────────────────────────────────
    // 그 일정이 없거나 내 것이 아님
    //
    // * 방문 기록과 같은 판단을 그대로 적용한 자리임
    //   조회를 accountId 와 함께 해서 남의 것과 없는 것을 구분하지 않음
    //   403 을 내면 그 stopId 가 존재한다는 사실을 알려주는 셈이 됨
    //
    // * VISIT_NOT_FOUND 를 재사용하지 않는 이유
    //   문구가 "없는 기록입니다" 라 일정에는 맞지 않음
    //   일정은 "담아 둔 것" 이고 방문 기록은 "다녀온 것" 이라 지우는 대상이 다름
    //   같은 코드를 쓰면 프론트가 어느 쪽 실패인지 가릴 수 없음
    //
    // * 수정과 삭제가 같은 코드를 씀
    //   둘 다 "그 일정을 찾지 못했다" 는 같은 상황임
    ITINERARY_NOT_FOUND(HttpStatus.NOT_FOUND, "이미 삭제되었거나 없는 일정입니다."),

    // 그 시각에 같은 장소가 이미 담겨 있음
    //
    // * 수정할 때만 나감
    //   담기는 같은 상태를 멱등으로 다뤄 기존 식별자를 돌려줌
    //   수정은 두 행을 하나로 합칠 수 없으므로 거부가 유일한 방법임
    //
    // * 왜 막는가
    //   담기에서 (계정, 장소, 방문 예정 일시) 가 모두 같은 것을 하나로 접어 두었는데
    //   수정으로 그 상태를 만들 수 있으면 규칙이 서 있지 않게 됨
    //
    // * 같은 장소를 하루에 두 번 담는 것 자체는 정상임
    //   오전에 들렀다가 저녁에 다시 가는 일정이 있을 수 있음
    //   막는 것은 시각까지 완전히 같은 경우뿐임
    //
    // * CommonErrorCode.VALIDATION_FAILED 를 쓰지 않는 이유
    //   그 코드의 일반적인 문구로는 무엇이 겹쳤는지가 드러나지 않음
    //   사용자가 고칠 수 있는 실패라 무엇을 고쳐야 하는지 문구에 담겨야 함
    ITINERARY_DUPLICATE(HttpStatus.BAD_REQUEST, "그 시각에 이미 같은 장소가 담겨 있습니다."),

    // ── 하루 요약 ─────────────────────────────────────────────
    // 같은 날짜를 너무 빨리 다시 만들려 함
    //
    // * 명세가 이름을 미리 정해 둔 코드임
    //   앞의 넷은 우리가 이름을 붙였지만 이 셋은 명세에 그대로 적혀 있음
    //
    // * 왜 공통 코드를 쓸 수 없는가
    //   CommonErrorCode 에 429 가 아예 없음
    //   요청이 잘못된 것이 아니라 너무 잦은 것이라 400 으로 내리면 뜻이 어긋남
    //
    // * 날짜별로 따로 셈
    //   9월 1일 요약을 만들고 바로 9월 2일 요약을 만드는 것은 막을 이유가 없음
    //   막는 것은 같은 날짜를 연달아 다시 만드는 경우뿐임
    SUMMARY_COOLDOWN(HttpStatus.TOO_MANY_REQUESTS, "잠시 후에 다시 시도해 주세요."),

    // 하루에 만들 수 있는 횟수를 다 씀
    //
    // * 여기서 세는 날짜는 "오늘" 이며 요약 대상 날짜가 아님
    //   지난 여행을 몰아서 요약하는 것도 같은 한도 안에서 이뤄짐
    //   사용량 제한이지 날짜별 제한이 아니기 때문임
    //
    // * 실패한 호출도 셈
    //   되돌리면 그 사이에 들어온 요청과 값이 어긋나고
    //   서버가 죽으면 되돌릴 기회 자체가 없어 영영 안 돌아옴
    //   상한의 목적이 남용 방지이지 성공 횟수 보장이 아님
    SUMMARY_DAILY_LIMIT(HttpStatus.TOO_MANY_REQUESTS, "오늘 만들 수 있는 요약을 다 썼습니다."),

    // 요약문을 만들지 못함
    //
    // * 요청 자체를 실패시키는 이유
    //   빈 문자열이나 잘린 문장을 저장하면 그것이 화면에 그대로 뜸
    //   다시 만들 수 있는 값이므로 저장하지 않고 사용자가 다시 누르게 하는 편이 나음
    //   방문 기록의 판정과는 반대임, 그쪽은 다시 만들 수 없어서 요청을 실패시켰음
    //
    // * 이 코드로 묶이는 경우 셋
    //   호출이 실패하거나 제한 시간을 넘김
    //   응답에서 요약문을 꺼내지 못함
    //   요약문이 정해진 길이를 넘김
    //     길이를 넘겼다는 것은 모델이 지시를 흘렸다는 뜻이라 그 결과를 남길 이유가 없음
    //     잘라서 저장하면 "평균 별점은 4." 처럼 끊긴 문장이 화면에 남음
    //
    // * 재시도하지 않음
    //   화면의 갱신 버튼이 곧 재시도임
    //   서버가 한 번 더 부르면 응답이 두 배로 길어져 로딩만 늘어남
    SUMMARY_GENERATION_FAILED(HttpStatus.BAD_GATEWAY, "요약을 만들지 못했습니다. 다시 시도해 주세요.");

    private final HttpStatus httpStatus;
    private final String message;

    UserErrorCode(HttpStatus httpStatus, String message) {
        this.httpStatus = httpStatus;
        this.message = message;
    }

    @Override
    public HttpStatus getHttpStatus() {
        return this.httpStatus;
    }

    @Override
    public String getCode() {
        return this.name();
    }

    @Override
    public String getMessage() {
        return this.message;
    }
}
