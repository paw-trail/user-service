package com.pawtrail.user.domain.repository;

import java.util.List;
import java.util.UUID;

/**
 * 최근에 본 장소를 담아 두는 약속입니다.
 *
 * 표를 만들지 않고 Redis 에 둡니다.
 * 최근 스물 곳만 남기면 되는 값이라 오래된 것이 밀려나야 하는데,
 * 데이터베이스에 두면 그 정리를 우리가 짜야 하고 남길 가치도 없는 이력이 쌓입니다.
 *
 * 지켜야 하는 것이 셋입니다.
 *   같은 장소가 두 번 들어가지 않을 것
 *   최근에 본 것이 앞에 올 것
 *   스무 곳까지만 남을 것
 * 어떤 자료구조로 그것을 지킬지는 구현이 정합니다.
 *
 * 수명을 두지 않습니다.
 * 오래됐다고 지울 이유가 없는 그 사람의 이력이고,
 * 계정당 식별자 스무 개라 아낄 메모리도 없습니다.
 * 대신 탈퇴할 때 반드시 지워야 합니다. 그것이 유일한 정리 경로입니다.
 */
public interface RecentPlaceStore {

    /**
     * 장소를 맨 앞에 놓습니다.
     *
     * 이미 있으면 그 자리가 맨 앞으로 옮겨집니다.
     * 목록에 두 번 나오지는 않습니다.
     * 그러지 않으면 카페 하나를 세 번 열었을 때 목록이 그 장소로 도배됩니다.
     *
     * 상한을 넘으면 뒤에서부터 밀려납니다.
     */
    void push(UUID accountId, UUID placeId);

    /**
     * 최근에 본 장소를 앞에서부터 돌려줍니다.
     *
     * 요청한 개수가 담아 둔 것보다 많으면 있는 만큼만 돌려줍니다.
     */
    List<UUID> findRecent(UUID accountId, int size);

    /**
     * 그 사람의 목록을 통째로 지웁니다.
     *
     * 탈퇴를 처리할 때 부릅니다.
     * 수명을 두지 않았으므로 이것을 부르지 않으면 목록이 영영 남습니다.
     */
    void deleteAll(UUID accountId);
}
