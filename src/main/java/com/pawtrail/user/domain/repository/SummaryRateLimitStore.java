package com.pawtrail.user.domain.repository;

import java.time.LocalDate;
import java.util.UUID;

/**
 * 하루 요약을 만드는 횟수를 세는 약속입니다.
 *
 * 두 가지를 함께 봅니다.
 *
 *   쿨다운   같은 날짜를 연달아 다시 만들지 못하게 함
 *   하루 상한 계정당 하루에 만들 수 있는 총량
 *
 * 하나만으로는 부족합니다.
 * 쿨다운만 있으면 날짜를 바꿔 가며 부르는 것을 못 막고,
 * 상한만 있으면 그 한도까지는 순식간에 몰아서 쓸 수 있습니다.
 *
 * 두 값이 세는 날짜가 다릅니다.
 *
 *   쿨다운   요약 대상 날짜.  9월 1일을 만들고 바로 9월 2일을 만드는 것은 막을 이유가 없음
 *   상한     오늘.           지난 여행을 몰아서 요약하는 것도 같은 한도 안에서 이뤄짐
 *
 * 왜 데이터베이스가 아닌가
 *
 * 상한을 셀 수가 없습니다.
 * 요약 표는 계정과 날짜가 함께 기본 키라 하루에 한 줄이고,
 * 같은 날짜를 스무 번 갱신해도 행은 하나이며 그 횟수가 어디에도 남지 않습니다.
 * 세려면 컬럼이나 표를 새로 만들어야 하는데 값이 저절로 사라져야 하는 성격이라 맞지 않습니다.
 *
 * 왜 "물어보기" 가 아니라 "자리 잡기" 인가
 *
 * 보낼 수 있는지 묻는 메서드와 썼다고 기록하는 메서드를 나누면
 * 그 사이에 모델 호출이 들어가 몇 초가 벌어집니다.
 * 그동안 저장소에는 아무 흔적도 없어 동시에 들어온 요청이 전부 확인을 통과합니다.
 *
 * 그래서 묻는 대신 자리를 잡습니다.
 * 자리를 잡은 요청만 호출로 넘어가고 나머지는 그 자리에서 돌아갑니다.
 * 인증 메일 발송 제한이 같은 구조를 쓰고 있습니다.
 */
public interface SummaryRateLimitStore {

    /**
     * 하루 한도를 하나 씁니다.
     *
     * 한도가 남아 있으면 참입니다.
     *
     * 세고 나서 판단합니다.
     * 읽은 뒤에 올리면 동시에 들어온 요청이 전부 같은 값을 읽어 다 통과합니다.
     * 쿨다운이 앞에서 막아 주지도 않습니다. 그쪽은 날짜별이라 다른 날짜끼리는 겹치지 않습니다.
     *
     * 실패해도 되돌리지 않습니다.
     * 되돌리는 사이에 다른 요청이 끼면 값이 어긋나고, 서버가 죽으면 되돌릴 기회가 없습니다.
     * 무엇보다 상한의 목적이 남용을 막는 것이지 성공 횟수를 보장하는 것이 아닙니다.
     * 실패한 호출도 모델을 부른 것은 맞으므로 세는 편이 사실에 가깝습니다.
     */
    boolean tryConsumeDailyLimit(UUID accountId);

    /**
     * 그 날짜의 쿨다운 자리를 잡습니다.
     *
     * 자리를 잡았으면 참이고, 그때만 모델을 부릅니다.
     * 아직 쿨다운이 남아 있으면 거짓입니다.
     *
     * 이 메서드는 저장소의 값을 바꿉니다.
     * 참을 받았으면 호출이 실패했을 때 releaseCooldown 으로 끝을 맺어야 합니다.
     */
    boolean tryAcquireCooldown(UUID accountId, LocalDate visitDate);

    /**
     * 잡아 둔 쿨다운을 돌려줍니다.
     *
     * 호출이 실패했을 때 부릅니다.
     * 그러지 않으면 요약을 받지도 못한 사람이 다음 시도를 기다리게 됩니다.
     * 제한 시간을 이미 기다린 뒤라 더 답답합니다.
     *
     * 돌려주어도 안전합니다.
     * 연달아 실패해도 하루 상한이 여전히 막고 있어 비용은 그 안에서 끝납니다.
     *
     * 하루 한도는 되돌리지 않습니다. 위에 적은 이유 그대로입니다.
     */
    void releaseCooldown(UUID accountId, LocalDate visitDate);
}
